/* ----------------------------------------------------------- спецификация */
function tpl_spec($doc, $D) {
    $C = $doc['company']; $P = $doc['party']; $par = doc_parent($doc, $D);
    $o = '<h1>Спецификация № ' . h($doc['n']) . '</h1>' .
         '<p class="sub">к Договору возмездного оказания услуг' . ($par ? ' № ' . h($par['n']) . ' от ' . h($par['date']) : '') . '</p>' .
         '<table class="hdr"><tr><td>Исполнитель: ' . h($C['short'] ?: $C['name']) . '<br>Заказчик: ' . h($P['short'] ?: $P['name']) . '</td><td class="r">' . crm_date_ru($doc['date']) . '</td></tr></table>';
    if (!empty($doc['title'])) $o .= '<p>' . nl2br(h($doc['title'])) . '</p>';
    $total = 0; $mtotal = 0;
    if (!empty($doc['items'])) {
        $o .= '<h2>1. Разовые услуги</h2>';
        [$t, $total] = tpl_items($doc['items']);
        $o .= $t . '<p class="tot">Итого разовые услуги: <b>' . crm_money($total) . ' ₽</b> (' . crm_words($total) . '). ' . h($C['tax']) . '.</p>';
    }
    if (!empty($doc['monthly'])) {
        $o .= '<h2>' . (!empty($doc['items']) ? '2' : '1') . '. Ежемесячные услуги</h2>';
        [$t, $mtotal] = tpl_monthly($doc['monthly']);
        $o .= $t . '<p class="tot">Итого в месяц: <b>' . crm_money($mtotal) . ' ₽</b> (' . crm_words($mtotal) . '). ' . h($C['tax']) . '.</p>';
    }
    $k = (!empty($doc['items']) ? 1 : 0) + (!empty($doc['monthly']) ? 1 : 0) + 1;
    $prepay = isset($doc['prepay']) && $doc['prepay'] !== '' ? (int)$doc['prepay'] : 50;
    $pts = [];
    if ($total > 0) {
        $pts[] = $prepay >= 100
            ? 'Разовые услуги оплачиваются полностью в течение 3 (трёх) рабочих дней после подписания настоящей Спецификации.'
            : ($prepay <= 0
                ? 'Разовые услуги оплачиваются в течение 3 (трёх) рабочих дней после подписания акта оказанных услуг.'
                : 'Разовые услуги: предоплата ' . $prepay . ' % — ' . crm_money(round($total * $prepay / 100, 2)) . ' ₽ в течение 3 (трёх) рабочих дней после подписания настоящей Спецификации; остаток ' . crm_money(round($total - $total * $prepay / 100, 2)) . ' ₽ — в течение 3 (трёх) рабочих дней после подписания акта оказанных услуг.');
        $pts[] = 'Срок оказания разовых услуг: ' . (!empty($doc['period']) ? h($doc['period']) : '10 (десять) рабочих дней с момента получения от Заказчика исходных данных и доступов') . '. Срок продлевается на время задержек согласований и предоставления материалов Заказчиком.';
    }
    if ($mtotal > 0) {
        $pts[] = 'Ежемесячные услуги оплачиваются авансом до 5 (пятого) числа оплачиваемого месяца по счёту Исполнителя, начиная с месяца, указанного в графе «Начало». Акт за месяц направляется до 5 (пятого) числа следующего месяца.';
        $pts[] = 'Рекламный бюджет Яндекс Директа оплачивается Заказчиком самостоятельно со своего аккаунта и в стоимость услуг не входит.';
    }
    $pts[] = 'Работы сверх согласованного объёма выполняются по отдельной спецификации или по ставке 2 000 ₽ за час после согласования с Заказчиком.';
    $o .= '<h2>' . $k . '. Условия оплаты и сроки</h2>';
    $n = 1; foreach ($pts as $p) { $o .= '<p class="pt"><b>' . $k . '.' . $n . '.</b> ' . $p . '</p>'; $n++; }
    if (!empty($doc['note'])) $o .= '<p class="pt">' . nl2br(h($doc['note'])) . '</p>';
    $o .= '<p class="pt">Спецификация вступает в силу с даты подписания и является неотъемлемой частью Договора.</p>' . tpl_sign($C, $P, false);
    return $o;
}

