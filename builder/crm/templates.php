function tpl_invoice($doc, $D) {
    $C = $doc['company']; $P = $doc['party']; $par = doc_parent($doc, $D);
    $o = '<table class="bank"><tr><td class="l">Банк получателя<br><b>' . h($C['bank'] ?: '—') . '</b></td><td>БИК<br>к/с</td><td><b>' . h($C['bik'] ?: '—') . '</b><br>' . h($C['ks'] ?: '—') . '</td></tr>' .
         '<tr><td class="l">Получатель<br><b>' . h($C['name']) . '</b><br>ИНН ' . h($C['inn']) . '</td><td>р/с</td><td><b>' . h($C['rs'] ?: '—') . '</b></td></tr></table>' .
         '<h1>Счёт на оплату № ' . h($doc['n']) . ' от ' . h($doc['date']) . '</h1>' .
         '<table class="hdr"><tr><td class="k">Поставщик:</td><td><b>' . h($C['name']) . '</b>, ИНН ' . h($C['inn']) . ', ' . h($C['address']) . '</td></tr>' .
         '<tr><td class="k">Покупатель:</td><td><b>' . h($P['name']) . '</b>' . (!empty($P['inn']) ? ', ИНН ' . h($P['inn']) : '') . (!empty($P['address']) ? ', ' . h($P['address']) : '') . '</td></tr>' .
         '<tr><td class="k">Основание:</td><td>' . h($doc['basis'] ?: ($par ? 'Договор № ' . $par['n'] . ' от ' . $par['date'] : '')) . '</td></tr></table>';
    [$t, $total] = tpl_items($doc['items'] ?? []);
    $o .= $t . '<p class="tot">Итого: <b>' . crm_money($total) . ' ₽</b><br>' . h($C['tax']) . '.</p>' .
          '<p>Всего наименований ' . count($doc['items'] ?? []) . ', на сумму ' . crm_money($total) . ' ₽.<br><b>' . crm_words($total) . '</b></p>' .
          (!empty($doc['due']) ? '<p>Оплатить до ' . h($doc['due']) . '. В назначении платежа укажите: «Оплата по счёту № ' . h($doc['n']) . ' от ' . h($doc['date']) . '».</p>' : '<p>В назначении платежа укажите: «Оплата по счёту № ' . h($doc['n']) . ' от ' . h($doc['date']) . '».</p>') .
          '<p class="sig1">Предприниматель _____________________ / ' . h($C['signer_short']) . ' /</p>';
    if (!empty($C['rs']) && !empty($C['bik']) && $total > 0) {
        /* QR для оплаты по ГОСТ Р 56042-2014 (ST00012 = UTF-8): банковские приложения читают его в разделе «Оплата по QR». */
        $qr = 'ST00012|Name=' . $C['name'] . '|PersonalAcc=' . $C['rs'] . '|BankName=' . $C['bank'] . '|BIC=' . $C['bik'] . '|CorrespAcc=' . $C['ks'] .
              '|PayeeINN=' . $C['inn'] . '|Sum=' . (int)round($total * 100) . '|Purpose=' . 'Оплата по счёту № ' . $doc['n'] . ' от ' . $doc['date'] . '. НДС не облагается';
        $o .= '<table class="qr"><tr><td class="code"><div data-qr="' . h($qr) . '"></div></td><td class="txt"><b>Оплата по QR-коду</b><br>Откройте приложение своего банка → «Оплатить по QR» и наведите камеру: реквизиты, сумма и назначение подставятся сами. Подходит для оплаты с расчётного счёта и с карты.</td></tr></table>';
    }
    return $o;
}

/* ------------------------------------------------------------------- акт */
function tpl_act($doc, $D) {
    $C = $doc['company']; $P = $doc['party']; $par = doc_parent($doc, $D);
    $o = '<h1>Акт оказанных услуг № ' . h($doc['n']) . ' от ' . h($doc['date']) . '</h1>' .
         '<table class="hdr"><tr><td class="k">Исполнитель:</td><td><b>' . h($C['name']) . '</b>, ИНН ' . h($C['inn']) . ', ' . h($C['address']) . '</td></tr>' .
         '<tr><td class="k">Заказчик:</td><td><b>' . h($P['name']) . '</b>' . (!empty($P['inn']) ? ', ИНН ' . h($P['inn']) : '') . (!empty($P['address']) ? ', ' . h($P['address']) : '') . '</td></tr>' .
         '<tr><td class="k">Основание:</td><td>' . h($doc['basis'] ?: ($par ? 'Договор № ' . $par['n'] . ' от ' . $par['date'] : '')) . '</td></tr>' .
         (!empty($doc['period']) ? '<tr><td class="k">Период:</td><td>' . h($doc['period']) . '</td></tr>' : '') . '</table>';
    [$t, $total] = tpl_items($doc['items'] ?? []);
    $o .= $t . '<p class="tot">Итого: <b>' . crm_money($total) . ' ₽</b> (' . crm_words($total) . '). ' . h($C['tax']) . '.</p>' .
          '<p class="pt">Вышеперечисленные услуги оказаны полностью и в срок. Заказчик претензий по объёму, качеству и срокам оказания услуг не имеет.</p>' .
          (!empty($doc['note']) ? '<p class="pt">' . nl2br(h($doc['note'])) . '</p>' : '') .
          tpl_sign($C, $P, false);
    return $o;
}

function doc_render($doc, $D) {
    switch ($doc['type']) {
        case 'contract': return tpl_contract($doc, $D);
        case 'spec':     return tpl_spec($doc, $D);
        case 'invoice':  return tpl_invoice($doc, $D);
        default:         return tpl_act($doc, $D);
    }
}
