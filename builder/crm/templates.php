/* Печатные формы первички: договор, спецификация, счёт, акт. Возвращают HTML тела документа;
   обёртку (стили, кнопка печати) даёт doc.php. Реквизиты берутся из снимка в документе —
   что было на момент сохранения, то и печатается. */

function doc_title($doc) {
    $t = crm_doc_types()[$doc['type']] ?? 'Документ';
    return $t . ' № ' . $doc['n'] . ' от ' . $doc['date'];
}
function doc_parent($doc, $D) {
    if (empty($doc['parent'])) return null;
    $i = crm_doc_find($D, $doc['parent']);
    return $i < 0 ? null : $D['docs'][$i];
}
function tpl_req($p) {
    $rows = [];
    if (!empty($p['name']))    $rows[] = '<b>' . h($p['name']) . '</b>';
    if (!empty($p['inn']))     $rows[] = 'ИНН ' . h($p['inn']) . (!empty($p['kpp']) ? ', КПП ' . h($p['kpp']) : '');
    if (!empty($p['ogrn']))    $rows[] = (strlen($p['ogrn']) === 15 ? 'ОГРНИП ' : 'ОГРН ') . h($p['ogrn']);
    if (!empty($p['address'])) $rows[] = 'Адрес: ' . h($p['address']);
    if (!empty($p['rs']))      $rows[] = 'р/с ' . h($p['rs']) . (!empty($p['bank']) ? ' в ' . h($p['bank']) : '');
    if (!empty($p['bik']))     $rows[] = 'БИК ' . h($p['bik']) . (!empty($p['ks']) ? ', к/с ' . h($p['ks']) : '');
    if (!empty($p['phone']))   $rows[] = 'Тел.: ' . h($p['phone']);
    if (!empty($p['email']))   $rows[] = 'E-mail: ' . h($p['email']);
    return implode('<br>', $rows);
}
function tpl_sign($C, $P, $withReq = true) {
    $cell = function ($who, $p) use ($withReq) {
        return '<td><p class="who">' . $who . '</p>' . ($withReq ? '<p class="req">' . tpl_req($p) . '</p>' : '') .
            '<p class="sig">_____________________ / ' . h($p['signer_short'] ?? '') . ' /</p><p class="mp">М.П.</p></td>';
    };
    return '<table class="sign"><tr>' . $cell('Исполнитель', $C) . $cell('Заказчик', $P) . '</tr></table>';
}
function tpl_items($items, $unitCol = true) {
    $h = '<table class="grid"><thead><tr><th>№</th><th>Наименование услуги</th>' . ($unitCol ? '<th>Кол-во</th><th>Ед.</th>' : '') .
         '<th>Цена, ₽</th><th>Сумма, ₽</th></tr></thead><tbody>';
    $sum = 0; $i = 0;
    foreach ($items as $it) {
        $i++; $line = (float)$it['qty'] * (float)$it['price']; $sum += $line;
        $h .= '<tr><td class="c">' . $i . '</td><td>' . nl2br(h($it['name'])) . '</td>' .
              ($unitCol ? '<td class="c">' . h(rtrim(rtrim(number_format((float)$it['qty'], 2, ',', ' '), '0'), ',')) . '</td><td class="c">' . h($it['unit']) . '</td>' : '') .
              '<td class="r">' . crm_money($it['price']) . '</td><td class="r">' . crm_money($line) . '</td></tr>';
    }
    $h .= '</tbody></table>';
    return [$h, $sum];
}
function tpl_monthly($items) {
    $h = '<table class="grid"><thead><tr><th>№</th><th>Ежемесячная услуга</th><th>Стоимость в месяц, ₽</th><th>Начало</th></tr></thead><tbody>';
    $sum = 0; $i = 0;
    foreach ($items as $it) {
        $i++; $sum += (float)$it['price'];
        $h .= '<tr><td class="c">' . $i . '</td><td>' . nl2br(h($it['name'])) . '</td><td class="r">' . crm_money($it['price']) . '</td><td>' . h($it['start'] ?? '') . '</td></tr>';
    }
    $h .= '</tbody></table>';
    return [$h, $sum];
}

